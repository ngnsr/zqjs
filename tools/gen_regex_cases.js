function runCase(pattern, flags, input, start = 0) {
  const execFlags = flags.includes('y') ? flags + 'd' : flags + 'gd';
  const re = new RegExp(pattern, execFlags);
  re.lastIndex = start;
  const m = re.exec(input);
  const expected = m ? Array.from(m.indices, (r) => (r ? [r[0], r[1]] : null)) : null;
  return { pattern, flags, input, start, expected };
}

