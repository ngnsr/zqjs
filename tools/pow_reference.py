"""Correctly rounded reference values for x ** y.

Reads the inputs of tests/ops/pow.jsonl (generated by node) and writes
tests/ops/pow_reference.jsonl: [x bits, y bits, bits of the correctly rounded x ** y].
tests/ops_test.zig uses it to measure *accuracy* (distance from the true value), which is
a different property from agreement with node.

Procedure, per case:
  1. Convert x and y to Decimal exactly (Decimal(float) is exact: every double is a finite
     binary fraction, hence a finite decimal).
  2. Compute |x| ** y with the decimal module at PRECISIONS[0] significant digits, round-half-
     even. CPython documents this as "almost always correctly rounded" to that precision;
     we don't rely on "almost": step 5 detects any case where it would matter.
  3. Apply the sign (negative x with odd integer y).
  4. Round once to the nearest double with float(Decimal), which is correctly rounded
     (round-half-even), including overflow to infinity and gradual underflow.
  5. Self-check: repeat 2-4 at PRECISIONS[1] and require the same double. The two can only
     disagree if the true value lies within ~10^-60 (relative) of a rounding boundary between
     two doubles, i.e. if 60 digits are not enough to decide the rounding; the script then
     fails instead of writing a doubtful reference.

Only finite, non-zero x and y are included (plus negative x only with integer y);
results for special values are fixed by the spec and tested against node instead.

Usage:
    python3 tools/pow_reference.py          regenerate
    python3 tools/pow_reference.py --check  fail if the file is out of date
Needs only the Python 3 standard library.
"""
import json
import math
import os
import struct
import sys
from decimal import Decimal, InvalidOperation, Overflow, localcontext

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
INPUT = os.path.join(ROOT, "tests", "ops", "pow.jsonl")
OUTPUT = os.path.join(ROOT, "tests", "ops", "pow_reference.jsonl")

PRECISIONS = (60, 100)  # significant decimal digits: computation and self-check


def from_bits(h):
    return struct.unpack(">d", bytes.fromhex(h))[0]


def to_bits(x):
    return struct.pack(">d", x).hex()


def reference(x, y):
    """The correctly rounded x ** y, or None when not covered by this table."""
    if not (math.isfinite(x) and math.isfinite(y)) or x == 0 or y == 0:
        return None
    if x < 0 and y != math.floor(y):
        return None
    results = []
    for prec in PRECISIONS:
        with localcontext() as ctx:
            ctx.prec = prec
            ctx.Emax = 10**8  # wide exponent range: no decimal overflow/underflow before step 4
            ctx.Emin = -(10**8)
            ctx.traps[Overflow] = False
            try:
                t = Decimal(abs(x)) ** Decimal(y)  # step 1-2 (Decimal(float) is exact)
            except InvalidOperation:
                return None
            if x < 0 and int(y) % 2 == 1:
                t = -t  # step 3
            results.append(float(t))  # step 4
    if len(set(map(to_bits, results))) != 1:  # step 5
        raise SystemExit("reference unstable for %r ** %r: %r; raise PRECISIONS" % (x, y, results))
    return results[0]


def generate():
    lines = []
    with open(INPUT) as f:
        for line in f:
            if not line.strip():
                continue
            xb, yb, _ = json.loads(line)
            r = reference(from_bits(xb), from_bits(yb))
            if r is not None:
                lines.append(json.dumps([xb, yb, to_bits(r)]))
    return "\n".join(lines) + "\n"


def main():
    content = generate()
    if "--check" in sys.argv:
        ok = os.path.exists(OUTPUT) and open(OUTPUT).read() == content
        print("pow_reference.jsonl up to date" if ok else "pow_reference.jsonl out of date; run: python3 tools/pow_reference.py")
        sys.exit(0 if ok else 1)
    with open(OUTPUT, "w") as f:
        f.write(content)
    print("wrote tests/ops/pow_reference.jsonl (%d cases)" % content.count("\n"))


if __name__ == "__main__":
    main()
