// Generates src/runtime/builtin_names.zig: the own property names node (V8) gives the
// global object and each built-in object ZQJS models (DESIGN_DECISIONS D39).
//
// ZQJS uses them to classify a property or global lookup that its own built-ins don't
// answer: a name node *has* is Unsupported(builtin) (ZQJS can't reproduce its value or
// behaviour), a name node doesn't have is a plain miss (undefined / ReferenceError).
// Names alone never provide behaviour: implemented built-ins live in runtime/builtins.zig.
//
// Taken from a fresh vm context, the environment tests/harness/golden.js runs programs in,
// so node's own extras (process, require, console…) are not included.
//
//   node tools/gen_builtins.js          regenerate
//   node tools/gen_builtins.js --check  fail if the file differs (run by `zig build check-goldens`)
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { execFileSync } = require('child_process');

const out = path.join(__dirname, '..', 'src', 'runtime', 'builtin_names.zig');
const objects = vm.runInNewContext(`({
  global: globalThis,
  object_prototype: Object.prototype,
  array_prototype: Array.prototype,
  string_prototype: String.prototype,
  number_prototype: Number.prototype,
  boolean_prototype: Boolean.prototype,
  function_prototype: Function.prototype,
  object_constructor: Object,
  array_constructor: Array,
  map_constructor: Map,
  map_prototype: Map.prototype,
  set_constructor: Set,
  set_prototype: Set.prototype,
  math: Math,
})`);

const lines = [
  '//! GENERATED by tools/gen_builtins.js from node ' + process.versions.node.split('.')[0] + '.x; do not edit.',
  '//! Own property names node gives each built-in object (DESIGN_DECISIONS D39).',
  '',
  'const std = @import("std");',
  '',
  'pub const Builtin = enum {',
  ...Object.keys(objects).map((k) => `    ${k},`),
  '};',
  '',
  '/// Whether node gives `b` an own property called `name`.',
  'pub fn has(b: Builtin, name: []const u8) bool {',
  '    return switch (b) {',
  ...Object.keys(objects).map((k) => `        .${k} => ${k}.has(name),`),
  '    };',
  '}',
  '',
];
for (const [k, obj] of Object.entries(objects)) {
  const names = Object.getOwnPropertyNames(obj).sort();
  lines.push(`const ${k} = std.StaticStringMap(void).initComptime(.{`);
  for (const n of names) lines.push(`    .{${JSON.stringify(n)}},`);
  lines.push('});', '');
}

const formatted = execFileSync('zig', ['fmt', '--stdin'], { input: lines.join('\n'), encoding: 'utf8' });
if (process.argv.includes('--check')) {
  const ok = fs.existsSync(out) && fs.readFileSync(out, 'utf8') === formatted;
  console.log(ok ? 'builtin_names.zig up to date' : 'builtin_names.zig out of date; run: node tools/gen_builtins.js');
  process.exit(ok ? 0 : 1);
}
fs.writeFileSync(out, formatted);
console.log('wrote src/runtime/builtin_names.zig');
