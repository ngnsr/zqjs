// Generates src/runtime/pow_data.zig from musl's pow_data.c and exp_data.c, as bundled
// with the pinned Zig (found via `zig env`). See THIRD_PARTY_NOTICES.md.
// Usage:
//   node tools/gen_pow_data.js          regenerate src/runtime/pow_data.zig
//   node tools/gen_pow_data.js --check  fail if the file differs from what would be generated
// Refuses to run if the musl sources' SHA-256 differ from the pinned ones.
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const pinned = {
  'pow.c': 'b06f0a08d74fcff8cced7afa2c0e47e301e3e8a19c0de5becdec28cd7b014027',
  'pow_data.c': '2052ec913f9b4a2170a98a6fcbcd7694f5dec220036b00c36106a2b4b65a4c55',
  'exp_data.c': 'c55dff64e369fe816cd8ce367064989bb119f85783599680d1a329031c660689',
};
const root = path.join(__dirname, '..');
const out = path.join(root, 'src/runtime/pow_data.zig');

const libDir = /\.lib_dir = "([^"]+)"/.exec(execFileSync('zig', ['env'], { encoding: 'utf8' }))[1];
const musl = path.join(libDir, 'libc/musl/src/math');
const src = {};
for (const [file, hash] of Object.entries(pinned)) {
  const text = fs.readFileSync(path.join(musl, file), 'utf8');
  const actual = crypto.createHash('sha256').update(text).digest('hex');
  if (actual !== hash) {
    console.error(`${file}: SHA-256 ${actual} differs from the pinned ${hash}.\n` +
      'The bundled musl changed: review the upstream diff, then update the pins here and in THIRD_PARTY_NOTICES.md.');
    process.exit(1);
  }
  src[file] = text;
}

function one(re, text) {
  const m = re.exec(text);
  if (!m) throw new Error(`pattern not found: ${re}`);
  return m[1].trim();
}
const values = (block) => block.split('\n').map((l) => l.trim().replace(/,$/, ''))
  .filter((l) => l && !l.startsWith('//'));

const powC = src['pow_data.c'];
const expC = src['exp_data.c'];
const logPoly = values(one(/\.poly = \{(.*?)\},/s, powC));
const rows = [...powC.matchAll(/^A\(([^,]+), ([^,]+), ([^)]+)\)/gm)].map((m) => m.slice(1).map((s) => s.trim()));
const expPoly = values(one(/\.poly = \{(.*?)\},/s, expC));
const tabBlock = one(/\.tab = \{(.*?)\},\s*\};/s, expC).split('\n').map((l) => l.split('//')[0]).join('\n');
const tab = tabBlock.match(/0x[0-9a-f]+/g);
if (logPoly.length !== 7 || rows.length !== 128 || expPoly.length !== 4 || tab.length !== 256)
  throw new Error(`unexpected table sizes: ${logPoly.length} ${rows.length} ${expPoly.length} ${tab.length}`);
if (!expC.includes('#if EXP_USE_TOINT_NARROW')) throw new Error('exp_data.c layout changed');

const lines = [];
lines.push(
  '//! Constant tables for pow (src/runtime/pow.zig).',
  '//!',
  "//! GENERATED by tools/gen_pow_data.js from musl's src/math/pow_data.c and exp_data.c",
  '//! (bundled with Zig 0.17.1; hashes in THIRD_PARTY_NOTICES.md). Do not edit by hand.',
  '//! Copyright (c) 2018, Arm Limited. SPDX-License-Identifier: MIT',
  '',
  'pub const log_table_bits = 7;',
  'pub const exp_table_bits = 7;',
  '',
  '// ---- log part (pow_log_data)',
  `pub const ln2hi: f64 = ${one(/\.ln2hi = ([^,]+),/, powC)};`,
  `pub const ln2lo: f64 = ${one(/\.ln2lo = ([^,]+),/, powC)};`,
  '/// Coefficients of log1p(r) - r, scaled to match the evaluation (first coefficient is 1).',
  'pub const log_poly = [7]f64{',
  ...logPoly.map((p) => `    ${p},`),
  '};',
  '',
  'pub const LogEntry = struct { invc: f64, logc: f64, logctail: f64 };',
  'pub const log_tab = [128]LogEntry{',
  ...rows.map(([a, b, c]) => `    .{ .invc = ${a}, .logc = ${b}, .logctail = ${c} },`),
  '};',
  '',
  '// ---- exp part (exp_data)',
  `pub const invln2N: f64 = ${one(/\.invln2N = ([^,]+),/, expC).replace(' * N', ' * 128')};`,
  'pub const shift: f64 = 0x1.8p52; // EXP_USE_TOINT_NARROW == 0',
  `pub const negln2hiN: f64 = ${one(/\.negln2hiN = ([^,]+),/, expC)};`,
  `pub const negln2loN: f64 = ${one(/\.negln2loN = ([^,]+),/, expC)};`,
  '/// exp polynomial: the last four coefficients (C2..C5).',
  'pub const exp_poly = [4]f64{',
  ...expPoly.map((p) => `    ${p},`),
  '};',
  '/// 2^(k/N) ~= H[k] * (1 + T[k]): tab[2k] = bits of T[k], tab[2k+1] = bits of H[k] - (k << 45).',
  'pub const exp_tab = [256]u64{',
);
for (let i = 0; i < 256; i += 2) lines.push(`    ${tab[i]}, ${tab[i + 1]},`);
lines.push('};', '');

const formatted = execFileSync('zig', ['fmt', '--stdin'], { input: lines.join('\n'), encoding: 'utf8' });
if (process.argv.includes('--check')) {
  const ok = fs.existsSync(out) && fs.readFileSync(out, 'utf8') === formatted;
  console.log(ok ? 'pow_data.zig up to date' : 'pow_data.zig out of date; run: node tools/gen_pow_data.js');
  process.exit(ok ? 0 : 1);
}
fs.writeFileSync(out, formatted);
console.log('wrote src/runtime/pow_data.zig');
